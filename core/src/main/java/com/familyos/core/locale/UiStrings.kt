object UiStringsCatalog {

    private val cache = java.util.concurrent.ConcurrentHashMap<String, UiStrings>()

    fun forLang(lang: String): UiStrings {
        val key = AppLocale.normalize(lang)
        return cache.getOrPut(key) {
            when (key) {
                AppLocale.RU -> buildRu()
                AppLocale.SR -> buildSr()
                AppLocale.DE -> buildDe()
                AppLocale.FR -> buildFr()
                AppLocale.ES -> buildEs()
                AppLocale.UK -> buildUk()
                else -> buildEn()
            }
        }
    }

